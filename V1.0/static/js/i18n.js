    if (!translated && (match = trimmed.match(/^(\d+)\s+days?\s+ago$/i))) translated = `${digits(match[1])} روز پیش`;
    if (!translated && (match = trimmed.match(/^\+(\d+)d$/i))) translated = `${digits(match[1])}+ روز`;
